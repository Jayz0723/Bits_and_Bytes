const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('./browser.cjs');
const root = path.resolve(__dirname, '..');

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route(/^https?:/, route => route.abort());
    const profileUrl = pathToFileURL(path.join(root, 'pages/profile.html')).href;
    const cartUrl = pathToFileURL(path.join(root, 'pages/cart.html')).href;
    await page.goto(profileUrl + '#addresses');
    await page.evaluate(async () => registerDemoAccount('Taylor Shopper', 'taylor@example.com', 'test-only-password'));
    assert.equal(await page.locator('.nav-account-greeting').textContent(), 'Hi, Taylor Shopper');
    await page.click('.nav-account summary');
    assert.ok(await page.locator('.nav-account a[href="pages/profile.html#addresses"]').isVisible());
    await page.keyboard.press('Escape');
    for (const width of [1440, 1280, 1024, 768, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.waitForTimeout(250);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Greeting fits ' + width);
      if (width > 1320) assert.ok(await page.evaluate(() => document.querySelector('.nav-account').getBoundingClientRect().right <= document.querySelector('.store-toolbar').getBoundingClientRect().left), 'Account and cart do not overlap');
    }
    await page.setViewportSize({ width: 1440, height: 1000 });
    async function fillAddress(label, street, province = 'Metro Manila', city = 'Quezon City', barangay = 'Commonwealth') {
      await page.fill('#addressBookLabel', label);
      await page.fill('#checkoutFirstName', 'Taylor');
      await page.fill('#checkoutMiddleName', 'Anne');
      await page.fill('#checkoutSurname', 'Shopper');
      await page.fill('#checkoutPhone', '09171234567');
      await page.fill('#streetAddress', street);
      await page.selectOption('#provinceSelect', province);
      await page.selectOption('#citySelect', city);
      await page.selectOption('#barangaySelect', barangay);
    }
    await page.click('#addProfileAddress');
    await fillAddress('Home', '12 Home Street');
    assert.equal(await page.inputValue('#postalCode'), '1121');
    for (const width of [1440, 768, 390, 320]) {
      await page.setViewportSize({ width, height: 900 });
      assert.ok(await page.locator('#addressBookDialog').evaluate(element => element.scrollWidth <= element.clientWidth), 'Address editor fits ' + width);
      await page.screenshot({ path: path.join(root, 'images/previews/address-editor-' + width + '.png') });
    }
    await page.getByRole('button', { name: 'Save address', exact: true }).click();
    assert.equal(await page.locator('.saved-address').count(), 1);
    assert.equal(await page.locator('.saved-address-badge').textContent(), 'Default');
    await page.click('#addProfileAddress');
    await fillAddress('Work', '34 Office Road', 'Cebu', 'Cebu City', 'Lahug');
    await page.getByRole('button', { name: 'Save address', exact: true }).click();
    assert.equal(await page.locator('.saved-address').count(), 2);
    const work = page.locator('.saved-address').filter({ hasText: 'Work' });
    await work.getByRole('button', { name: 'Set as default' }).click();
    assert.ok(await work.locator('.saved-address-badge').isVisible());
    await work.getByRole('button', { name: 'Edit', exact: true }).click();
    assert.equal(await page.inputValue('#streetAddress'), '34 Office Road');
    await page.fill('#streetAddress', '56 Updated Office Road');
    await page.getByRole('button', { name: 'Save address', exact: true }).click();
    await page.reload();
    assert.equal(await page.locator('.saved-address').count(), 2, 'Multiple addresses persist');
    assert.match(await page.locator('.saved-address').filter({ hasText: 'Work' }).textContent(), /56 Updated Office Road/);
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.waitForTimeout(250);
    await page.screenshot({ path: path.join(root, 'images/previews/address-book-desktop.png'), fullPage: true });
    const book = await page.evaluate(() => getAddressBook());
    const homeId = book.addresses.find(entry => entry.label === 'Home').id;
    const workId = book.addresses.find(entry => entry.label === 'Work').id;
    await page.evaluate(async () => registerDemoAccount('Other Shopper', 'other-address@example.com', 'test-only-password'));
    assert.equal(await page.locator('.saved-address').count(), 0, 'Another account has no addresses');
    assert.equal(await page.evaluate(id => { try { setDefaultAddress(id); return false; } catch { return true; } }, homeId), true);
    await page.evaluate(async () => signInDemoAccount('taylor@example.com', 'test-only-password'));
    assert.equal(await page.locator('.saved-address').count(), 2);
    await page.evaluate(() => saveCart([{ ...catalogProducts()[0], quantity: 1 }]));
    await page.goto(cartUrl);
    await page.click('#checkoutButton');
    assert.equal(await page.inputValue('#checkoutSavedAddress'), workId);
    assert.equal(await page.inputValue('#streetAddress'), '56 Updated Office Road');
    assert.equal(await page.inputValue('#citySelect'), 'Cebu City');
    assert.equal(await page.inputValue('#postalCode'), '6000');
    await page.selectOption('#checkoutSavedAddress', homeId);
    assert.equal(await page.inputValue('#streetAddress'), '12 Home Street');
    assert.equal(await page.inputValue('#postalCode'), '1121');
    const subtotal = await page.evaluate(() => getCart().reduce((sum, item) => sum + item.price * item.quantity, 0));
    assert.equal(await page.locator('#checkoutGrandTotal').textContent(), await page.evaluate(value => paymentAmount(value), subtotal + 150));
    await page.check('[name="deliveryService"][value="express"]');
    assert.equal(await page.locator('#checkoutGrandTotal').textContent(), await page.evaluate(value => paymentAmount(value), subtotal + 300));
    await page.screenshot({ path: path.join(root, 'images/previews/express-checkout.png'), fullPage: true });
    await page.click('#reviewOrderButton');
    assert.match(await page.locator('#sampleDeliveryBreakdown').textContent(), /Express delivery/);
    await page.evaluate(() => { const radio = document.querySelector('[name="deliveryService"][value="standard"]'); radio.checked = true; radio.dispatchEvent(new Event('change')); });
    await page.click('#verifySamplePayment');
    assert.match(await page.locator('#samplePaymentError').textContent(), /delivery service has changed/);
    assert.equal(await page.evaluate(() => savedStoreOrders().length), 0);
    await page.keyboard.press('Escape');
    await page.check('[name="deliveryService"][value="express"]');
    await page.click('#reviewOrderButton');
    await page.click('#verifySamplePayment');
    await page.locator('#checkoutSuccess').waitFor({ state: 'visible' });
    const order = await page.evaluate(() => accountStoreOrders()[0]);
    assert.equal(order.delivery.service, 'express');
    assert.equal(order.delivery.fee, 300);
    assert.equal(order.total, subtotal + 300);
    assert.equal(order.subtotal, subtotal);
    assert.equal(order.address.street, '12 Home Street');
    await page.click('#continueToTracking');
    await page.locator('#trackingOrder').waitFor({ state: 'visible' });
    assert.match(await page.locator('#trackingSummary').textContent(), /Express delivery/);
    assert.match(await page.locator('#trackingSummary').textContent(), /300\.00/);
    await page.goto(profileUrl + '#addresses');
    await page.locator('.saved-address').filter({ hasText: 'Home' }).getByRole('button', { name: 'Edit', exact: true }).click();
    await page.fill('#streetAddress', '98 New Home Street');
    await page.getByRole('button', { name: 'Save address', exact: true }).click();
    assert.equal(await page.evaluate(() => accountStoreOrders()[0].address.street), '12 Home Street', 'Editing saved address does not rewrite order');
    page.once('dialog', dialog => dialog.accept());
    await page.locator('.saved-address').filter({ hasText: 'Work' }).getByRole('button', { name: 'Remove', exact: true }).click();
    assert.equal(await page.locator('.saved-address').count(), 1);
    assert.equal(await page.evaluate(() => getAddressBook().defaultId), homeId, 'Removing the default chooses another saved address');
    await page.reload();
    assert.equal(await page.locator('.saved-address').count(), 1);
    await page.click('#addProfileAddress');
    await page.evaluate(() => { sessionStorage.removeItem('bitsAndBytesSignedInEmail'); window.dispatchEvent(new Event('store-account-change')); });
    await page.locator('#addressBookDialog').waitFor({ state: 'detached' });
    assert.equal(await page.locator('#addressBookDialog').count(), 0, 'Sign-out closes editor');
    assert.equal(await page.locator('#profileAddressBook').textContent(), '');
    assert.equal(await page.locator('.nav-account-greeting').textContent(), 'My account');
    assert.deepEqual(errors, []);
    console.log('Passed account greeting/menu, responsive address editor, add/edit/default/remove, persistence, account isolation, checkout autofill, exact express pricing, changed-delivery rejection, tracking fee breakdown, immutable order addresses, and sign-out privacy.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
